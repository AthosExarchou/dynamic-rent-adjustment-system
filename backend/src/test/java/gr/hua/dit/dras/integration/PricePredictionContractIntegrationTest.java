package gr.hua.dit.dras.integration;

/* imports */
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import gr.hua.dit.dras.dto.PriceSuggestionDTO;
import gr.hua.dit.dras.dto.PriceSuggestionRequestDTO;
import gr.hua.dit.dras.model.enums.PropertyType;
import gr.hua.dit.dras.services.domain.PriceSuggestionService;
import gr.hua.dit.dras.services.infrastructure.EmailService;
import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.bean.override.mockito.MockitoBean;

import java.io.File;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

@SpringBootTest
class PricePredictionContractIntegrationTest {

    @Autowired
    private PriceSuggestionService priceSuggestionService;

    @Autowired
    private ObjectMapper objectMapper;

    @MockitoBean
    private EmailService emailService;

    private File locatePredictionFile() {
        List<Path> candidatePaths = List.of(
                Paths.get("..", "analytics", "outputs", "price_predictions.json"),
                Paths.get("analytics", "outputs", "price_predictions.json")
        );

        for (Path p : candidatePaths) {
            File f = p.toFile();
            if (f.exists() && f.canRead()) {
                return f;
            }
        }

        return null;
    }

    @Test
    @DisplayName("Analytics ARIMA output JSON file complies with PriceSuggestionService contract")
    void pricePredictionFile_CompliesWithContract() throws Exception {
        File file = locatePredictionFile();
        Assumptions.assumeTrue(file != null && file.exists(),
                "Skipping test: analytics/outputs/price_predictions.json not yet generated by analytics pipeline");

        JsonNode root = objectMapper.readTree(file);
        assertThat(root).isNotNull();

        // Root structure
        assertThat(root.has("version")).as("Root must contain 'version'").isTrue();
        assertThat(root.has("arimaForecast")).as("Root must contain 'arimaForecast'").isTrue();
        assertThat(root.has("scrapedMarketBenchmarks")).as("Root must contain 'scrapedMarketBenchmarks'").isTrue();

        // arimaForecast contract
        JsonNode arima = root.get("arimaForecast");
        assertThat(arima.has("predictedPricePerM2")).isTrue();
        assertThat(arima.get("predictedPricePerM2").asDouble()).isGreaterThan(0.0);

        assertThat(arima.has("lowerBoundPerM2")).isTrue();
        assertThat(arima.get("lowerBoundPerM2").asDouble()).isGreaterThan(0.0);

        assertThat(arima.has("upperBoundPerM2")).isTrue();
        assertThat(arima.get("upperBoundPerM2").asDouble())
                .isGreaterThanOrEqualTo(arima.get("lowerBoundPerM2").asDouble());

        assertThat(arima.has("trend")).isTrue();
        assertThat(arima.get("trend").asText()).isIn("UPWARD", "DOWNWARD", "STABLE");

        assertThat(arima.has("trendPercentage")).isTrue();
        assertThat(arima.has("horizonWeeks")).isTrue();
        assertThat(arima.get("horizonWeeks").asInt()).isGreaterThan(0);

        assertThat(arima.has("weeklyForecast")).isTrue();
        assertThat(arima.get("weeklyForecast").isArray()).isTrue();
        assertThat(arima.get("weeklyForecast").size()).isGreaterThan(0);

        // scrapedMarketBenchmarks contract
        JsonNode benchmarks = root.get("scrapedMarketBenchmarks");
        assertThat(benchmarks.has("overallAvgPricePerM2")).isTrue();
        assertThat(benchmarks.get("overallAvgPricePerM2").asDouble()).isGreaterThan(0.0);

        assertThat(benchmarks.has("overallMedianPricePerM2")).isTrue();
        assertThat(benchmarks.get("overallMedianPricePerM2").asDouble()).isGreaterThan(0.0);

        assertThat(benchmarks.has("totalScrapedListings")).isTrue();
        assertThat(benchmarks.get("totalScrapedListings").asInt()).isGreaterThan(0);

        assertThat(benchmarks.has("byPropertyType")).isTrue();
        assertThat(benchmarks.get("byPropertyType").isObject()).isTrue();
        assertThat(benchmarks.get("byPropertyType").has("APARTMENT")).isTrue();
        assertThat(benchmarks.get("byPropertyType").get("APARTMENT").has("avgPricePerM2")).isTrue();

        assertThat(benchmarks.has("byArea")).isTrue();
        assertThat(benchmarks.get("byArea").isObject()).isTrue();
    }

    @Test
    @DisplayName("PriceSuggestionService produces model-driven suggestions using live prediction file")
    void priceSuggestionService_UsesLivePredictionData() throws Exception {
        File file = locatePredictionFile();
        Assumptions.assumeTrue(file != null && file.exists(),
                "Skipping test: analytics/outputs/price_predictions.json not yet generated by analytics pipeline");

        JsonNode root = objectMapper.readTree(file);
        assertThat(root).isNotNull();

        double expectedPredictedPricePerM2 = root.get("arimaForecast").get("predictedPricePerM2").asDouble();

        PriceSuggestionRequestDTO request = new PriceSuggestionRequestDTO();
        request.setSizeM2(75);
        request.setPropertyType(PropertyType.APARTMENT);
        request.setAddress("Kolonaki, Athens");
        request.setYearBuilt(2015);
        request.setFloor(3);
        request.setBedrooms(2);
        request.setBathrooms(1);

        PriceSuggestionDTO suggestion = priceSuggestionService.suggestPrice(request);

        assertThat(suggestion).isNotNull();
        assertThat(suggestion.getSuggestedPrice()).isNotNull();
        assertThat(suggestion.getSuggestedPrice()).isGreaterThan(0);
        assertThat(suggestion.getSuggestedPricePerM2()).isGreaterThan(0.0);
        assertThat(suggestion.getMinPrice()).isNotNull();
        assertThat(suggestion.getMaxPrice()).isNotNull();
        assertThat(suggestion.getMaxPrice()).isGreaterThanOrEqualTo(suggestion.getMinPrice());

        assertThat(suggestion.getArimaForecast()).isNotNull();
        assertThat(suggestion.getArimaForecast().getModelStatus()).isEqualTo("ARIMA");
        assertThat(suggestion.getArimaForecast().getConfidenceLevel()).isEqualTo(0.95);
        assertThat(suggestion.getArimaForecast().getPredictedPricePerM2()).isEqualTo(expectedPredictedPricePerM2);

        assertThat(suggestion.getMarketBenchmark()).isNotNull();
        assertThat(suggestion.getMarketBenchmark().getAvgPricePerM2()).isGreaterThan(0.0);
    }
}
